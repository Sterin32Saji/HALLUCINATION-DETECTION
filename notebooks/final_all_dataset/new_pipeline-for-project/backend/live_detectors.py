from __future__ import annotations

import re
from functools import lru_cache

import numpy as np
from datasets import Dataset
from langchain_community.embeddings import HuggingFaceEmbeddings
from langchain_core.prompts import ChatPromptTemplate
from langchain_ollama import ChatOllama
from ragas import evaluate
from ragas.metrics import faithfulness

from config import RAGAS_THRESHOLD, SIMILARITY_THRESHOLD


OLLAMA_MODEL = "qwen2.5:7b"
EMBEDDING_MODEL = "sentence-transformers/all-MiniLM-L6-v2"
N_SELFCHECK_SAMPLES = 3


@lru_cache(maxsize=1)
def _baseline_chain():
    llm = ChatOllama(model=OLLAMA_MODEL, temperature=0)
    evaluator_prompt = ChatPromptTemplate.from_template(
        """
You are an expert evaluator for a Retrieval-Augmented Generation (RAG) system.
Your task is to compare the "Generated Answer" against the provided "Evidence" to detect hallucinations.

A "hallucination" is defined as ANY of the following:
1. The generated answer states facts, numbers, or entities not present in the evidence.
2. The generated answer contradicts the evidence.
3. The generated answer claims the evidence lacks the information, but the evidence actually contains it.

<evidence>
{evidence}
</evidence>

<generated_answer>
{rag_answer}
</generated_answer>

Does the generated answer contain a hallucination based strictly on the provided evidence?
Respond ONLY with a single digit:
1 (if hallucination is detected)
0 (if the answer is fully faithful to the evidence or accurately states the evidence lacks the info)
"""
    )
    return evaluator_prompt | llm


@lru_cache(maxsize=1)
def _selfcheck_components():
    judge_llm = ChatOllama(model=OLLAMA_MODEL, temperature=0.0)
    sampler_llm = ChatOllama(model=OLLAMA_MODEL, temperature=1.0)

    sample_prompt = ChatPromptTemplate.from_template("Question: {question}\nAnswer:")
    judge_prompt = ChatPromptTemplate.from_template(
        """
You are analyzing a response for factual consistency against a set of alternative answers to detect hallucinations.

<target_answer>
{rag_answer}
</target_answer>

Here are {n_samples} alternative answers generated by the same model for the question: "{question}"
<alternative_samples>
{combined_samples}
</alternative_samples>

Does the <target_answer> contain facts, claims, or specific details that are completely unmentioned or contradicted by the majority of the alternative samples?
If the target answer contains unverified or conflicting information compared to the samples, classify it as a hallucination.

Respond ONLY with a single digit:
1 (if a hallucination/inconsistency is detected)
0 (if the answer is consistent and verified by the samples)
"""
    )
    return sample_prompt, judge_prompt, sampler_llm, judge_llm


@lru_cache(maxsize=1)
def _ragas_components():
    local_llm = ChatOllama(model=OLLAMA_MODEL, temperature=0)
    local_embeddings = HuggingFaceEmbeddings(model_name=EMBEDDING_MODEL)
    return local_llm, local_embeddings


@lru_cache(maxsize=1)
def _embedding_model():
    return HuggingFaceEmbeddings(model_name=EMBEDDING_MODEL)


def _extract_binary_score(response_obj) -> int:
    text = response_obj.content.strip()
    match = re.search(r"[01]", text)
    if match:
        return int(match.group())
    return -1


def _compute_baseline(evidence: str, rag_answer: str) -> int:
    if not rag_answer:
        return 1

    response = _baseline_chain().invoke({"evidence": evidence, "rag_answer": rag_answer})
    score = _extract_binary_score(response)

    if score in (0, 1):
        return score
    return 1


def _compute_selfcheck(question: str, rag_answer: str) -> tuple[int, list[str]]:
    if not rag_answer:
        return 1, []

    sample_prompt, judge_prompt, sampler_llm, judge_llm = _selfcheck_components()

    samples = []
    for idx in range(N_SELFCHECK_SAMPLES):
        response = (sample_prompt | sampler_llm).invoke({"question": question})
        samples.append(f"Sample {idx + 1}: {response.content.strip()}")

    combined_samples = "\n\n".join(samples)
    judge_response = (judge_prompt | judge_llm).invoke(
        {
            "rag_answer": rag_answer,
            "question": question,
            "n_samples": N_SELFCHECK_SAMPLES,
            "combined_samples": combined_samples,
        }
    )

    raw_score = judge_response.content.strip()
    hallucination_score = 1 if "1" in raw_score else 0
    return hallucination_score, samples


def _compute_similarity(evidence: str, rag_answer: str) -> float:
    if not evidence.strip() or not rag_answer.strip():
        return 0.0

    model = _embedding_model()
    v1 = np.array(model.embed_query(evidence))
    v2 = np.array(model.embed_query(rag_answer))

    dot_product = np.dot(v1, v2)
    norm_v1 = np.linalg.norm(v1)
    norm_v2 = np.linalg.norm(v2)

    if norm_v1 == 0 or norm_v2 == 0:
        return 0.0

    return float(dot_product / (norm_v1 * norm_v2))


def _compute_ragas(question: str, evidence: str, rag_answer: str) -> float:
    if not rag_answer:
        return 0.0

    local_llm, local_embeddings = _ragas_components()

    context_list = [str(item) for item in evidence] if isinstance(evidence, list) else [str(evidence)]
    data_samples = {
        "question": [str(question)],
        "contexts": [context_list],
        "answer": [str(rag_answer)],
    }

    single_item_dataset = Dataset.from_dict(data_samples)

    result = evaluate(
        dataset=single_item_dataset,
        metrics=[faithfulness],
        llm=local_llm,
        embeddings=local_embeddings,
        show_progress=False,
    )

    score_df = result.to_pandas()
    return float(score_df["faithfulness"].iloc[0])


def compute_all_detectors(raw: dict) -> dict:
    rid = str(raw.get("id") or "sample")
    question = str(raw.get("question") or "")
    rag_answer = str(raw.get("rag_answer") or "")

    raw_evidence = raw.get("evidence", "")
    if isinstance(raw_evidence, list):
        evidence_text = " ".join([str(item) for item in raw_evidence])
    else:
        evidence_text = str(raw_evidence)

    baseline = _compute_baseline(evidence_text, rag_answer)
    selfcheck, samples = _compute_selfcheck(question, rag_answer)
    ragas_raw = _compute_ragas(question, raw_evidence, rag_answer)
    similarity_raw = _compute_similarity(evidence_text, rag_answer)

    return {
        "id": rid,
        "question": raw.get("question"),
        "answer": raw.get("answer"),
        "evidence": raw.get("evidence"),
        "rag_answer": raw.get("rag_answer"),
        "baseline": int(baseline),
        "selfcheck": int(selfcheck),
        "ragas_raw_faithfulness": float(ragas_raw),
        "similarity_raw_score": float(similarity_raw),
        "ragas": 1 if ragas_raw < RAGAS_THRESHOLD else 0,
        "similarity": 1 if similarity_raw < SIMILARITY_THRESHOLD else 0,
        "detector_debug": {
            "source": "live-detector-computation",
            "selfcheck_samples": samples,
        },
    }
